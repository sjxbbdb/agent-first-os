#ifndef AGENT_OS_SEMANTIC_REGISTRY_PROTOCOL_H
#define AGENT_OS_SEMANTIC_REGISTRY_PROTOCOL_H

/* Minimal native Ring 3 Semantic Registry protocol. */
#include <stdint.h>

#define AGENT_OS_SEMANTIC_REGISTRY_QUERY UINT32_C(0x80)
#define AGENT_OS_SEMANTIC_CONTEXT_CAPTURE UINT32_C(0x81)
#define AGENT_OS_SEMANTIC_ACTION_BIND UINT32_C(0x82)
#define AGENT_OS_SEMANTIC_TRUSTED_INPUT UINT32_C(0x83)

#define AGENT_OS_SEMANTIC_REPLY_DENY UINT32_C(0x9f)
#define AGENT_OS_SEMANTIC_REPLY_TOOL UINT32_C(0x90)
#define AGENT_OS_SEMANTIC_REPLY_CONTEXT UINT32_C(0x91)
#define AGENT_OS_SEMANTIC_REPLY_ACTION UINT32_C(0x92)
#define AGENT_OS_SEMANTIC_REPLY_TRUSTED_INPUT UINT32_C(0x93)
#define AGENT_OS_SEMANTIC_UNSUPPORTED_OPCODE UINT32_C(0x7f)
#define AGENT_OS_SEMANTIC_WRONG_ACTION_DIGEST UINT64_C(0xbadac71000000001)

/* Stable fixture identifiers; a real registry uses cryptographic digests. */
#define AGENT_OS_SEMANTIC_UNKNOWN_TOOL UINT64_C(0xdeadbeef)
#define AGENT_OS_SEMANTIC_TOOL_ID UINT64_C(0x7368656c6c2e7772)
#define AGENT_OS_SEMANTIC_TOOL_METADATA UINT64_C(0x0100000000000001)
#define AGENT_OS_SEMANTIC_WINDOW_ID UINT64_C(0x5441534b2d303031)
#define AGENT_OS_SEMANTIC_CONTEXT_DIGEST UINT64_C(0x0c0ffee000000001)
#define AGENT_OS_SEMANTIC_ACTION_DIGEST UINT64_C(0x0a11ce0000000001)
#define AGENT_OS_SEMANTIC_TRUSTED_NONCE UINT64_C(0x5452555354454401)

#endif
